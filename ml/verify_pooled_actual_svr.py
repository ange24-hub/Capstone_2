"""Independent arithmetic/leakage audit, with an additional simple baseline diagnostic."""
import argparse
import hashlib
import json
from pathlib import Path
import joblib
import numpy as np
from ml.train_pooled_actual_svr import feature_frame, metrics, render_report, write


def verify(out):
    source_path = out/'reconstructed-source.json'
    source = json.loads(source_path.read_text(encoding='utf-8'))
    result_path = out/'pooled-result.json'
    result = json.loads(result_path.read_text(encoding='utf-8'))
    assert result['source_sha256'] == hashlib.sha256(source_path.read_bytes()).hexdigest()
    rows = sorted(source['experimental_arrival_samples'], key=lambda r: (r['month'], r['barangay_id']))
    sample = result['recorded_arrival_sample_svr']
    split = sample['training_rows']
    model_file = out/'sample-svr/evaluation-model.joblib'
    frozen = json.loads((out/'sample-svr/frozen-before-scoring.json').read_text())
    assert frozen['model_sha256'] == hashlib.sha256(model_file.read_bytes()).hexdigest()
    assert frozen['test_used_for_parameter_selection'] is False
    model = joblib.load(model_file)  # Trusted artifact generated by this local run only.
    x = feature_frame(rows)
    actual = np.array([r['count'] for r in rows[split:]], dtype=float)
    raw_prediction = model.predict(x.iloc[split:])
    prediction = np.maximum(0., raw_prediction)
    saved = np.array([r['svr_prediction'] for r in sample['test_predictions']])
    assert np.allclose(prediction, saved, rtol=0, atol=1e-12)
    errors = actual - prediction
    assert abs(float(np.mean(np.abs(errors))) - sample['mae']) < 1e-12
    assert abs(float(np.sqrt(np.mean(np.square(errors)))) - sample['rmse']) < 1e-12
    expected_mean = x.iloc[:split][['month_sin','month_cos','previous_observed','previous_missing','gap_months']].mean().to_numpy()
    assert np.allclose(model.named_steps['preprocess'].named_transformers_['numeric'].mean_, expected_mean)
    assert max(rows[i]['month'] for i in range(split)) < min(rows[i]['month'] for i in range(split, len(rows)))
    assert all(r['complete_physical_migration_total'] is False for r in rows)
    assert result['actual_municipal_in_svr']['mae'] is None and result['actual_municipal_out_svr']['rmse'] is None
    assert result['synthetic_training_rows'] == result['age_inferred_training_labels'] == 0
    mean = float(np.mean([r['count'] for r in rows[:split]]))
    # Added as a diagnostic after the first run. It never changes the SVR settings/artifact.
    diagnostic = {'name': 'Frozen pooled training mean; additional diagnostic, not used for selection',
                  'training_mean': mean, **metrics(actual, np.repeat(mean, len(actual))),
                  'svr_settings_changed': False}
    if not (out/'pooled-result-before-diagnostic.json').exists():
        (out/'pooled-result-before-diagnostic.json').write_bytes(result_path.read_bytes())
    result['additional_training_mean_baseline'] = diagnostic
    for row, raw in zip(sample['test_predictions'], raw_prediction):
        row['raw_svr_prediction'] = float(raw)
    write(result_path, result)
    verification = {'passed': True, 'source_sha256': result['source_sha256'], 'model_sha256': frozen['model_sha256'],
        'metrics_recomputed_independently': True, 'scaler_uses_training_only': True,
        'same_date_area_rows_not_split': True, 'unknown_target_months_not_zero_filled': True,
        'additional_training_mean_baseline': diagnostic, 'source_records_changed': False}
    write(out/'independent-verification.json', verification)
    workbook = json.loads((out/'workbook-review-summary.json').read_text())
    render_report(out, source, result, workbook)
    return verification


if __name__ == '__main__':
    parser = argparse.ArgumentParser(); parser.add_argument('directory', type=Path)
    print(json.dumps(verify(parser.parse_args().directory), indent=2))
